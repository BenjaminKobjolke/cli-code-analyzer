"""PHP-CS-Fixer analyze rule for PHP code style checking"""

import re
import subprocess
from pathlib import Path

from models import RuleResult
from rules.php_cs_fixer_report import (
    drop_fixer_from_json,
    report_fixer_output,
    run_fixer_commands,
)
from rules.php_tool_paths import get_bundled_php_tool_path
from rules.project_wide_rule import ProjectWideRule

# Default paths to exclude if none specified
DEFAULT_EXCLUDE_PATHS = ['vendor', '.git']

# Config file names in order of priority
GENERATED_FIXER_CONFIG = '.php-cs-fixer.dist.php'
FIXER_CONFIG_FILES = [GENERATED_FIXER_CONFIG, '.php-cs-fixer.php']

# First line of every config this rule writes; files without it belong to the user
GENERATED_MARKER = '// Auto-generated by cli-code-analyzer'

LINE_ENDINGS = {'lf': '\\n', 'crlf': '\\r\\n'}


def _git_config(base_path: Path, key: str) -> str:
    """Read a git config value for the repo at base_path ('' if unset or no git)."""
    try:
        result = subprocess.run(
            ['git', 'config', '--get', key],
            cwd=base_path, capture_output=True, text=True, timeout=10, check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return ''
    return result.stdout.strip().lower()


def git_normalizes_line_endings(base_path: Path) -> bool:
    """Whether git converts line endings to LF on commit for the repo at base_path.

    With core.autocrlf=true (or core.eol=crlf) the checked-out files are CRLF while
    files written later by editors/tools are often LF; git stores both as LF, so the
    working-tree line ending of a file does not matter.
    """
    if _git_config(base_path, 'core.autocrlf') in ('true', 'input'):
        return True
    return _git_config(base_path, 'core.eol') == 'crlf'


class PHPCSFixerAnalyzeRule(ProjectWideRule):
    """Rule to analyze PHP code style using PHP-CS-Fixer in dry-run mode"""

    rule_name = 'php_cs_fixer'

    def _get_exclude_paths(self) -> list[str]:
        """Get exclude paths from config, with defaults if not specified."""
        if isinstance(self.config, str):
            return DEFAULT_EXCLUDE_PATHS.copy()
        return self.config.get('exclude_paths', DEFAULT_EXCLUDE_PATHS.copy())

    def _get_rules(self) -> str:
        """Get rules from config."""
        if isinstance(self.config, str):
            return self.config
        return self.config.get('rules', '@PSR12')

    def _line_ending_setting(self) -> str:
        """Configured line_ending: 'lf', 'crlf' or 'auto' (default)."""
        setting = 'auto' if isinstance(self.config, str) else str(self.config.get('line_ending', 'auto')).lower()
        if setting not in LINE_ENDINGS and setting != 'auto':
            self.logger.warning(f"  Warning: Unknown line_ending '{setting}', using auto")
            return 'auto'
        return setting

    def _get_line_ending(self) -> str:
        """Line ending written into the generated config ('auto' = LF, what git stores)."""
        setting = self._line_ending_setting()
        return setting if setting in LINE_ENDINGS else 'lf'

    def _reports_line_ending(self) -> bool:
        """Whether line_ending fixes are reported.

        'auto' drops them when git normalizes line endings on commit (a Windows
        checkout mixes CRLF files from git with LF files written by tools). The fixer
        itself stays enabled: it runs first and normalizes the content in memory, so
        the whitespace fixers (braces_position, single_blank_line_at_eof, ...) see
        consistent line endings; disabling it makes them flag every CRLF file.
        """
        if self._line_ending_setting() in LINE_ENDINGS:
            return True
        return not git_normalizes_line_endings(self.base_path)

    def _is_managed(self) -> bool:
        """Check if config file management is enabled (default: True)."""
        if isinstance(self.config, str):
            return True
        return self.config.get('managed', True)

    def _get_fixer_config_path(self) -> Path | None:
        """Find existing PHP-CS-Fixer config file in the project."""
        for config_name in FIXER_CONFIG_FILES:
            config_path = self.base_path / config_name
            if config_path.exists():
                return config_path
        return None

    def _parse_fixer_config_excludes(self, config_content: str) -> list[str]:
        """Parse exclude paths from existing PHP-CS-Fixer config file.

        Looks for patterns like:
            ->exclude(['vendor', 'storage'])
            ->exclude(["vendor", "storage"])
        """
        excludes = []
        # Match ->exclude([...]) with single or double quotes
        pattern = r"->exclude\s*\(\s*\[(.*?)\]\s*\)"
        match = re.search(pattern, config_content, re.DOTALL)
        if match:
            items_str = match.group(1)
            # Extract quoted strings
            items = re.findall(r"['\"]([^'\"]+)['\"]", items_str)
            excludes.extend(items)
        return excludes

    def _generate_fixer_config(self, exclude_paths: list[str], rules: str, line_ending: str = 'lf') -> str:
        """Generate PHP-CS-Fixer config file content."""
        # Use forward slashes for PHP (works on all platforms)
        exclude_list = ", ".join(f"'{p}'" for p in exclude_paths)

        return f'''<?php
{GENERATED_MARKER}
// Modify php_cs_fixer (rules, exclude_paths, line_ending) in code_analysis_rules.json and re-run to update
// Set "managed": false in your config to prevent auto-updates

$finder = PhpCsFixer\\Finder::create()
    ->in(__DIR__)
    ->exclude([{exclude_list}]);

return (new PhpCsFixer\\Config())
    ->setRules(['{rules}' => true])
    ->setLineEnding("{LINE_ENDINGS[line_ending]}")
    ->setFinder($finder);
'''

    def _create_fixer_config(self, content: str) -> Path:
        """Create a new PHP-CS-Fixer config file."""
        config_path = self.base_path / GENERATED_FIXER_CONFIG
        config_path.write_text(content, encoding='utf-8', newline='\n')
        self.logger.info(f"  Created config: {config_path.name}")
        return config_path

    def _update_fixer_config(self, config_path: Path, new_content: str) -> bool:
        """Rewrite a generated config whose content differs from the current settings.

        Configs without the generated marker belong to the user and are left alone.
        Returns True if config was updated, False if no update needed.
        """
        try:
            content = config_path.read_text(encoding='utf-8')
            if GENERATED_MARKER not in content:
                self.logger.info(f"  Using existing config: {config_path.name} (not generated by the analyzer)")
                return False

            if content.replace('\r\n', '\n') == new_content:
                return False

            config_path.write_text(new_content, encoding='utf-8', newline='\n')
            self.logger.info(f"  Updated config: {config_path.name}")
            old_excludes = self._parse_fixer_config_excludes(content)
            new_excludes = self._parse_fixer_config_excludes(new_content)
            if set(old_excludes) != set(new_excludes):
                self.logger.info(f"    Old excludes: {old_excludes}")
                self.logger.info(f"    New excludes: {new_excludes}")
            return True

        except Exception as e:
            self.logger.warning(f"  Warning: Could not update config {config_path.name}: {e}")
            return False

    def _ensure_fixer_config(self) -> Path | None:
        """Ensure PHP-CS-Fixer config exists with correct exclude paths.

        Returns the path to the config file, or None if management is disabled.
        """
        if not self._is_managed():
            existing = self._get_fixer_config_path()
            if existing:
                self.logger.info(f"  Using existing config: {existing.name} (managed=false)")
            return existing

        content = self._generate_fixer_config(
            self._get_exclude_paths(), self._get_rules(), self._get_line_ending()
        )

        existing_config = self._get_fixer_config_path()

        if existing_config:
            # Check and update if needed
            self._update_fixer_config(existing_config, content)
            return existing_config
        else:
            # Create new config
            return self._create_fixer_config(content)

    def _run(self, _file_path: Path) -> RuleResult:
        self.logger.info("\nRunning PHP-CS-Fixer check...")

        # First check bundled php/vendor/bin folder
        fixer_path = get_bundled_php_tool_path('php-cs-fixer')
        if not fixer_path:
            fixer_path = self._get_tool_path('php-cs-fixer', 'php_cs_fixer')
        if not fixer_path:
            return self._failed("PHP-CS-Fixer executable not found")

        return self._run_fixer_check(fixer_path)

    def _run_fixer_check(self, fixer_path: str) -> RuleResult:
        """Execute PHP-CS-Fixer in dry-run mode and parse results."""
        # Ensure config file exists with correct exclude paths
        config_path = self._ensure_fixer_config()

        # Get analysis path
        if isinstance(self.config, str):
            analyze_path = str(self.base_path)
        else:
            analyze_path = self.config.get('analyze_path', str(self.base_path))

        # Resolve relative path
        if not Path(analyze_path).is_absolute():
            analyze_path = str(self.base_path / analyze_path)

        # Build command
        cmd = [fixer_path, 'fix', '--dry-run', '--format=json', '--verbose', '--show-progress=none', '--no-interaction']

        # Use config file if available, otherwise use --rules
        if config_path:
            # --path-mode=intersection so the explicit analyze path does not
            # override the config Finder's ->exclude([...]) (default override
            # mode discards those excludes, e.g. cache/ would be scanned).
            cmd.extend(['--config', str(config_path), '--path-mode=intersection'])
        else:
            rules = self._get_rules()
            if rules:
                cmd.extend(['--rules', rules])

        # Print scanning info
        exclude_paths = self._get_exclude_paths()
        rules = self._get_rules()
        self.logger.info(f"  Scanning: {analyze_path}")
        self.logger.info(f"  Excluding: {', '.join(exclude_paths)}")
        self.logger.info(f"  Rules: {rules}")
        reports_line_ending = self._reports_line_ending()
        if config_path:
            note = '' if reports_line_ending else ' (line_ending fixes not reported, git normalizes on commit)'
            self.logger.info(f"  Line ending: {self._get_line_ending()}{note}")

        try:
            commands = self._scoped_commands(
                cmd,
                ('.php',),
                [analyze_path],
                exclude=lambda path: not path.resolve().is_relative_to(Path(analyze_path).resolve()),
            )
            if commands is None:
                self.logger.info(f"Skipping PHP-CS-Fixer: no changed PHP files inside {analyze_path}")
                return self._ok([])

            output = run_fixer_commands(
                commands, self._run_subprocess, self.base_path, self.filter_files is not None, self.logger
            )
            if not reports_line_ending:
                output = drop_fixer_from_json(output, 'line_ending')

            violations = report_fixer_output(
                output,
                self._get_relative_path,
                self.logger,
                self._filter_violations_by_log_level,
                self.max_errors,
                self.output_folder,
            )

            return self._ok(violations)

        except FileNotFoundError:
            self.logger.error(f"Error: PHP-CS-Fixer executable not found: {fixer_path}")
            self.logger.error("Please ensure PHP-CS-Fixer is installed: composer require --dev friendsofphp/php-cs-fixer")
            return self._failed(f"PHP-CS-Fixer executable not found: {fixer_path}")
        except Exception as e:
            self.logger.error(f"Error running PHP-CS-Fixer check: {e}")
            return self._failed(f"error running PHP-CS-Fixer check: {e}")
